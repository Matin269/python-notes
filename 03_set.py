# بدون ترتیب و ایندکس
# قابل تغییر (mutable)
# تکراری را بی صدا نادیده میگیرد (بر اساس هش)
# عضو ها باید hashable باشد
# هش رشته در هر اجرا تغییر میکند

my_set = {1, 2, 3}

# ---------------------------------------------------Empty Set
print(type({}))  # دیکشنری ساخته میشه
print(type(set()))  # ست ساخته میشه
# ---------------------------------------------------Hashable
ok = {1, "salam", (3, 5), frozenset({7, 4})}  # کاملا درست
# bad = {1, [1, 2]}  # TypeError: لیست قابل قبول نیست
# ست دو چیز را برسی میکند. برابری و هش
hash(5)  # هش یک ابجکت را برمیگرداند
# اگر هم هش و هم مقدار یکی باشد تکراری حساب شده و اولین شکل عضو را نمایش میدهد
# عدد ۱ و ۱.۰ و True همه هش ۱ دارند و تکراری محسوب میشوند
num_1 = {1, True, 1.0}  # همه یکی هستند
# ---------------------------------------------------Collision
# هش یکسان و مقدار متفاوت باگ نیست
# ---------------------------------------------------Add
my_set.add("Hi")  # یک عضو Hi اضافه میکند
# تک تک عناصر را جدا جدا اضافه میکند که تکراری ها را نادیده میگیرد
my_set.update([3, 6, 2])
# ^^^^^ -> اگر یک عنصر غیر قابل پیمایش مانند ۵ بدهیم خطا میدهد
# ---------------------------------------------------Delete
my_set.remove("Hi")  # اگر ورودی تابع در ست وجود نداشته باشد خطا میدهد
my_set.discard(573409)  # اگر ورودی تابع در ست وجود نداشته باشد بی صدا رد میشود
ok.pop()  # یک عضو را رندوم حذف و برمیگرداند
ok.clear()  # به طور کامل ست را خالی میکند ولی خود ست باقی میماند
# ریمو عنصر ناموجد و پاپ روی ست خالی خطای KeyError میدهد
# ---------------------------------------------------Information and Search
num_set = {1, 4, 5, 8}
print(len(num_set))  # تعداد عضو های ست را برمیگرداند
# کوچک ترین و بزرگ ترین و جمع عضو ها
print(min(num_set), max(num_set), sum(num_set))
print("Hello" if 4 in num_set else "Bye")
# In در ست سریع تر از لیست است
# ---------------------------------------------------Mathematical Operations
a = {1, 2, 3, 4}
b = {3, 4, 5, 6}
print(a | b)  # اجماع (union)
print(a & b)  # اشتراک (intersection)
print(a - b)  # تفاضل. اشتراک را از اولی حذف میکند (difference)
print(a ^ b)  # تفاضل متقارن. اجماع منهای اشتراک (symmetric_difference)
# ^^^^^^^^ -> فقط ست قبول میکنند
a |= b  # اجماع درجا (update)
a &= b  # اشتراک درجا(intersection_update)
a -= b  # تفاضل درجا (difference_update)
a ^= b  # تفاضل متقارن درجا (symmetric_difference_update)
# ^^^^^^^^ -> همه عمل های بالا ابتدا مثل قبل حساب میشوند و نتیجه مقدار جدید ست اول خواهد بود
# ---------------------------------------------------Comparison
a = {1, 2}
b = {1, 2, 3, 4}
print(a <= b)  # زیر مجموعه (issubset)
print(b >= a)  # ابر مجموعه (issuperset)
print(a < b)  # زیر مجموعه اکید
print(a.isdisjoint({6}))  # اشتراک خالی
# ^^^^^^^^^ -> هر ست زیر مجموعه خودش هست ولی اکید نه
# ست خالی زیر مجموعه هر ستی حتی خودش و حتی isdisjoint است
# a <= [1, 2]  # TypeError
a.issubset([1, 2])  # کاملا درست
# ---------------------------------------------------Copy
c = a  # کپی نشده و فقط دو اسم به یک ست اشاره میکنند
c = a.copy()  # کپی مستقل (shallow)
# ^^^^ -> چون اکثر عضو های ست غیر قابل تغییر هستند زیاد مشکل ست تو در تو پیش نمی آید
#         و به deepcopy نیاز نیست
# ---------------------------------------------------Frozenset
fs = frozenset([1, 2, 3, 4])  # مانند ست عادی ولی غیر قابل تغییر
# fs.add(4)  # AttributeError
print(fs == {1, 2, 3, 4})  # تفاوتی ندارند و جواب True است

